#!/bin/bash

# ==========================================================
# HYBRID TERRAFORM + CLOUDFORMATION AWS LAB
# EC2 Environment Verification Script
# ==========================================================

echo "=================================================="
echo " EC2 Environment Verification"
echo "=================================================="


# ----------------------------------------------------------
# Operating system
# ----------------------------------------------------------

echo ""
echo ">>> Operating System"

cat /etc/os-release


# ----------------------------------------------------------
# Kernel
# ----------------------------------------------------------

echo ""
echo ">>> Kernel"

uname -r


# ----------------------------------------------------------
# CPU
# ----------------------------------------------------------

echo ""
echo ">>> CPU"

nproc


# ----------------------------------------------------------
# Memory
# ----------------------------------------------------------

echo ""
echo ">>> Memory"

free -h


# ----------------------------------------------------------
# Disk
# ----------------------------------------------------------

echo ""
echo ">>> Disk"

df -h


# ----------------------------------------------------------
# Git
# ----------------------------------------------------------

echo ""
echo ">>> Git"

git --version


# ----------------------------------------------------------
# AWS CLI
# ----------------------------------------------------------

echo ""
echo ">>> AWS CLI"

aws --version


# ----------------------------------------------------------
# Docker
# ----------------------------------------------------------

echo ""
echo ">>> Docker"

docker --version


# ----------------------------------------------------------
# Docker service
# ----------------------------------------------------------

echo ""
echo ">>> Docker Service"

systemctl is-active docker


# ----------------------------------------------------------
# AWS identity
# ----------------------------------------------------------

echo ""
echo ">>> AWS Identity"

aws sts get-caller-identity


# ----------------------------------------------------------
# EC2 metadata
# ----------------------------------------------------------

echo ""
echo ">>> EC2 Instance Information"

TOKEN=$(curl -sX PUT \
    "http://169.254.169.254/latest/api/token" \
    -H "X-aws-ec2-metadata-token-ttl-seconds: 21600")

INSTANCE_ID=$(curl -s \
    -H "X-aws-ec2-metadata-token: $TOKEN" \
    "http://169.254.169.254/latest/meta-data/instance-id")

PRIVATE_IP=$(curl -s \
    -H "X-aws-ec2-metadata-token: $TOKEN" \
    "http://169.254.169.254/latest/meta-data/local-ipv4")

echo "Instance ID : $INSTANCE_ID"
echo "Private IP  : $PRIVATE_IP"


# ----------------------------------------------------------
# Docker containers
# ----------------------------------------------------------

echo ""
echo ">>> Docker Containers"

docker ps -a


echo ""
echo "=================================================="
echo " Verification completed."
echo "=================================================="